package com.a9.arbor.grc.modules.auditmgmt.service;

import com.a9.arbor.grc.modules.auditmgmt.domain.FindingSeverity;
import com.a9.arbor.grc.modules.auditmgmt.domain.GrcAudit;
import com.a9.arbor.grc.modules.auditmgmt.domain.GrcAuditChecklistItem;
import com.a9.arbor.grc.modules.auditmgmt.domain.GrcAuditFinding;
import com.a9.arbor.grc.modules.export.PdfText;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.springframework.stereotype.Component;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

/**
 * Formal audit report: cover, results, scope, findings, and the full working paper.
 * Standard 14 fonts, with text mapped so close and export do not fail on punctuation.
 */
@Component
public class AuditReportPdfWriter {

    private static final float MARGIN = 48f;
    private static final float FOOTER = 40f;
    private static final float[] GOLD = {184f / 255f, 134f / 255f, 11f / 255f};
    private static final float[] INK = {28f / 255f, 25f / 255f, 23f / 255f};
    private static final float[] MUTED = {82f / 255f, 82f / 255f, 91f / 255f};
    private static final float[] SAND = {250f / 255f, 247f / 255f, 242f / 255f};
    private static final float[] HAIR = {228f / 255f, 228f / 255f, 231f / 255f};

    public byte[] write(AuditReportData data) {
        try (PDDocument doc = new PDDocument()) {
            String title = AuditReportLabels.reportTitle(data.audit().getAuditType());
            doc.getDocumentInformation().setTitle(PdfText.oneLine(title + " " + data.audit().getDisplayId()));
            doc.getDocumentInformation().setAuthor(PdfText.oneLine(data.organisation()));
            doc.getDocumentInformation().setSubject(PdfText.oneLine(data.audit().getName()));

            PDType1Font regular = new PDType1Font(Standard14Fonts.FontName.HELVETICA);
            PDType1Font bold = new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD);
            Canvas canvas = new Canvas(doc, regular, bold, data);
            canvas.cover();
            canvas.body();
            canvas.closeStream();
            canvas.stampFooters();

            ByteArrayOutputStream out = new ByteArrayOutputStream();
            doc.save(out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new IllegalStateException("Could not export the audit report", e);
        }
    }

    private static final class Canvas {
        private final PDDocument doc;
        private final PDType1Font regular;
        private final PDType1Font bold;
        private final AuditReportData data;
        private PDPage page;
        private PDPageContentStream stream;
        private float y;

        Canvas(PDDocument doc, PDType1Font regular, PDType1Font bold, AuditReportData data) {
            this.doc = doc;
            this.regular = regular;
            this.bold = bold;
            this.data = data;
        }

        void cover() throws IOException {
            newPage(true);
            GrcAudit audit = data.audit();
            text(AuditReportLabels.reportTitle(audit.getAuditType()).toUpperCase(), bold, 9f, GOLD, 14f);
            gap(4);
            for (String line : wrap(AuditReportLabels.dash(data.organisation()), regular, 11f, contentWidth())) {
                text(line, regular, 11f, MUTED, 16f);
            }
            gap(8);
            for (String line : wrap(AuditReportLabels.dash(audit.getName()), bold, 20f, contentWidth())) {
                text(line, bold, 20f, INK, 24f);
            }
            gap(2);
            text(AuditReportLabels.dash(audit.getDisplayId()), regular, 11f, MUTED, 16f);
            gap(8);
            rule();
            gap(10);
            metaRow("Status", AuditReportLabels.statusLabel(audit.getStatus(), data.findings().size()),
                    "Type", AuditReportLabels.typeLabel(audit.getAuditType()));
            metaRow("Framework", data.frameworkLine(),
                    "Mode", AuditReportLabels.modeLabel(audit.getAuditMode()));
            metaRow("Period", AuditReportLabels.period(audit.getStartDate(), audit.getEndDate()),
                    "Lead auditor", person(data.leadName(), data.leadEmail()));
            metaRow("Auditee", AuditReportLabels.dash(data.auditeeName()),
                    "Checklists", data.checklistNames());
            metaRow("Generated", AuditReportLabels.instant(data.generatedAt()),
                    "Generated by", AuditReportLabels.dash(data.generatedBy()));
            gap(6);
            section("Results");
            stats();
            gap(4);
            text(severityLine(), regular, 9f, MUTED, 13f);
        }

        void body() throws IOException {
            newPage(false);
            section("Scope");
            field("Modules in scope", data.scopeModules().isEmpty() ? "-" : String.join(", ", data.scopeModules()));
            field("Scope notes", AuditReportLabels.dash(data.audit().getScopeNotes()));
            field("Control subset", data.scopeNodeCount() == 0 ? "-" : data.scopeNodeCount() + " controls");
            field("Auditor organisation", AuditReportLabels.dash(data.audit().getAuditorOrganisation()));

            section("Team");
            if (data.team().isEmpty()) {
                text("No team members recorded.", regular, 10f, INK, 14f);
            } else {
                for (AuditReportData.TeamMember member : data.team()) {
                    field(member.role(), person(member.name(), member.email()));
                }
            }

            section("Executive summary");
            paragraphs(AuditReportLabels.dash(data.audit().getExecutiveSummary()));

            if (!data.narratives().isEmpty()) {
                section("Domain narratives");
                for (AuditReportData.DomainNarrative narrative : data.narratives()) {
                    String heading = AuditReportLabels.dash(narrative.code());
                    if (narrative.name() != null && !narrative.name().isBlank()) {
                        heading = heading.equals("-") ? narrative.name().trim() : heading + "  " + narrative.name().trim();
                    }
                    text(heading, bold, 10f, INK, 14f);
                    paragraphs(AuditReportLabels.dash(narrative.narrative()));
                    gap(4);
                }
            }

            section("Findings");
            if (data.findings().isEmpty()) {
                text("No findings recorded.", regular, 10f, INK, 14f);
            } else {
                for (AuditReportData.FindingLine line : data.findings()) {
                    finding(line);
                }
            }

            section("Working paper");
            if (data.sheets().isEmpty()) {
                text("No checklist on this audit.", regular, 10f, INK, 14f);
            } else {
                for (AuditReportData.ChecklistSheet sheet : data.sheets()) {
                    for (String line : wrap(sheet.name() + "  (" + sheet.items().size() + ")", bold, 11f, contentWidth())) {
                        text(line, bold, 11f, INK, 16f);
                    }
                    gap(2);
                    if (sheet.items().isEmpty()) {
                        text("No controls on this checklist.", regular, 10f, MUTED, 14f);
                    } else {
                        for (GrcAuditChecklistItem item : sheet.items()) {
                            control(item);
                        }
                    }
                    gap(6);
                }
            }

            section("Signatures");
            signature("Lead auditor", data.auditorSignedBy(), data.audit().getAuditorSignedAt());
            gap(8);
            signature("Administrator", data.adminSignedBy(), data.audit().getAdminSignedAt());
        }

        private void finding(AuditReportData.FindingLine line) throws IOException {
            GrcAuditFinding f = line.finding();
            ensure(48);
            rule();
            gap(6);
            String head = AuditReportLabels.dash(f.getDisplayCode()) + "   " + AuditReportLabels.severity(f.getSeverity());
            text(head, bold, 11f, INK, 15f);
            for (String wrapped : wrap(AuditReportLabels.dash(f.getTitle()), bold, 10.5f, contentWidth())) {
                text(wrapped, bold, 10.5f, INK, 14f);
            }
            field("Clause / Ref", AuditReportLabels.dash(line.clauseRef()));
            field("Control", AuditReportLabels.dash(f.getControlRef()));
            field("Raised", AuditReportLabels.instant(f.getCreatedAt()));
            field("CAPA", AuditReportLabels.dash(line.capaLabel()));
            field("Description", AuditReportLabels.dash(f.getDescription()));
            field("Recommended action", AuditReportLabels.dash(f.getRecommendedAction()));
            gap(8);
        }

        private void control(GrcAuditChecklistItem item) throws IOException {
            ensure(56);
            gap(4);
            rule();
            gap(4);
            text(AuditReportLabels.dash(item.getNodeCode()), bold, 9f, GOLD, 12f);
            for (String line : wrap(AuditReportLabels.dash(item.getTitle()), bold, 10.5f, contentWidth())) {
                text(line, bold, 10.5f, INK, 14f);
            }
            field("Section", AuditReportLabels.dash(item.getSection()));
            field("Test focus", AuditReportLabels.dash(item.getTestFocus()));
            field("SoA / type", AuditReportLabels.dash(item.getSoaApplicability()));
            field("Evidence source", AuditReportLabels.dash(item.getEvidenceModule()));
            field("In scope", AuditReportLabels.yesNo(item.isInScope()));
            field("Conclusion", AuditReportLabels.conclusion(item.getConclusion()));
            field("Self-assessment", AuditReportLabels.assessment(item.getAssessment()));
            field("Finding ID", findingCode(item));
            field("Finding description", data.includeWorkingNotes()
                    ? AuditReportLabels.dash(item.getFindingDescription()) : "-");
            field("Auditor note", data.includeWorkingNotes() ? AuditReportLabels.dash(item.getNotes()) : "-");
            field("Evidence examined", data.includeWorkingNotes()
                    ? AuditReportLabels.dash(item.getEvidenceExamined()) : "-");
            field("Persons interviewed", AuditReportLabels.dash(item.getPersonsInterviewed()));
            field("Date reviewed", AuditReportLabels.date(item.getReviewedDate()));
            gap(6);
        }

        private String findingCode(GrcAuditChecklistItem item) {
            if (item.getFindingId() == null) {
                return "-";
            }
            for (AuditReportData.FindingLine line : data.findings()) {
                if (item.getFindingId().equals(line.finding().getId())) {
                    return AuditReportLabels.dash(line.finding().getDisplayCode());
                }
            }
            return "-";
        }

        private void signature(String role, String name, java.time.Instant at) throws IOException {
            ensure(52);
            text(role, bold, 10f, INK, 14f);
            text(name == null || name.isBlank() ? "Not signed" : name.trim(), regular, 10f, INK, 14f);
            text(at == null ? "Date: -" : "Date: " + AuditReportLabels.instant(at), regular, 9f, MUTED, 13f);
            gap(2);
            strokeH(MARGIN, y, 220f, INK);
            y -= 8f;
        }

        private void stats() throws IOException {
            String[] labels = {"Controls in scope", "Reviewed", "Still open", "Findings"};
            String[] values = {
                    String.valueOf(data.controlsInScope()),
                    String.valueOf(data.reviewed()),
                    String.valueOf(data.stillOpen()),
                    String.valueOf(data.findings().size())
            };
            float gapPx = 8f;
            float boxW = (contentWidth() - gapPx * 3) / 4f;
            float boxH = 44f;
            ensure(boxH + 8);
            float top = y;
            for (int i = 0; i < 4; i++) {
                float x = MARGIN + i * (boxW + gapPx);
                fill(x, top - boxH, boxW, boxH, SAND);
                strokeRect(x, top - boxH, boxW, boxH, HAIR);
                draw(x + 8f, top - 20f, values[i], bold, 14f, INK);
                draw(x + 8f, top - 34f, labels[i], regular, 7.5f, MUTED);
            }
            y = top - boxH - 8f;
        }

        private String severityLine() {
            int major = 0;
            int minor = 0;
            int observation = 0;
            int ofi = 0;
            for (AuditReportData.FindingLine line : data.findings()) {
                FindingSeverity severity = line.finding().getSeverity();
                if (severity == FindingSeverity.MAJOR_NC) {
                    major++;
                } else if (severity == FindingSeverity.MINOR_NC) {
                    minor++;
                } else if (severity == FindingSeverity.OBSERVATION) {
                    observation++;
                } else if (severity == FindingSeverity.OFI) {
                    ofi++;
                }
            }
            return "Major NC: " + major
                    + "    Minor NC: " + minor
                    + "    Observation: " + observation
                    + "    OFI: " + ofi;
        }

        private void metaRow(String l1, String v1, String l2, String v2) throws IOException {
            float colGap = 18f;
            float colW = (contentWidth() - colGap) / 2f;
            ensure(32);
            float start = y;
            float left = metaCell(MARGIN, start, colW, l1, v1);
            float right = metaCell(MARGIN + colW + colGap, start, colW, l2, v2);
            y = Math.min(left, right) - 6f;
        }

        private float metaCell(float x, float top, float width, String label, String value) throws IOException {
            draw(x, top - 9f, label.toUpperCase(), bold, 7.5f, MUTED);
            float cursor = top - 22f;
            for (String line : wrap(value, regular, 10f, width)) {
                draw(x, cursor, line, regular, 10f, INK);
                cursor -= 13f;
            }
            return cursor;
        }

        private void section(String title) throws IOException {
            ensure(32);
            gap(6);
            float h = 18f;
            fill(MARGIN, y - h, contentWidth(), h, SAND);
            fill(MARGIN, y - h, 3f, h, GOLD);
            draw(MARGIN + 10f, y - 13f, title, bold, 11f, INK);
            y -= h + 8f;
        }

        private void field(String label, String value) throws IOException {
            String body = label + ": " + (value == null || value.isBlank() ? "-" : value.trim());
            paragraphs(body);
        }

        private void paragraphs(String value) throws IOException {
            String safe = PdfText.sanitize(value == null ? "" : value);
            if (safe.isBlank()) {
                text("-", regular, 10f, INK, 13f);
                return;
            }
            String[] blocks = safe.split("\\n");
            for (String block : blocks) {
                String trimmed = block.trim();
                if (trimmed.isEmpty()) {
                    gap(4);
                    continue;
                }
                for (String line : wrap(trimmed, regular, 10f, contentWidth())) {
                    text(line, regular, 10f, INK, 13f);
                }
            }
        }

        private void text(String value, PDType1Font font, float size, float[] color, float leading) throws IOException {
            ensure(leading);
            draw(MARGIN, y - size, PdfText.oneLine(value), font, size, color);
            y -= leading;
        }

        private void draw(float x, float baseline, String value, PDType1Font font, float size, float[] color)
                throws IOException {
            stream.setNonStrokingColor(color[0], color[1], color[2]);
            stream.beginText();
            stream.setFont(font, size);
            stream.newLineAtOffset(x, baseline);
            stream.showText(value == null || value.isEmpty() ? "-" : value);
            stream.endText();
        }

        private void rule() throws IOException {
            ensure(8);
            strokeH(MARGIN, y, contentWidth(), GOLD);
            y -= 2f;
        }

        private void gap(float n) {
            y -= n;
        }

        private void newPage(boolean cover) throws IOException {
            closeStream();
            page = new PDPage(PDRectangle.A4);
            doc.addPage(page);
            stream = new PDPageContentStream(doc, page);
            float top = page.getMediaBox().getHeight();
            if (cover) {
                fill(0, top - 8f, page.getMediaBox().getWidth(), 8f, GOLD);
                y = top - 36f;
            } else {
                fill(0, top - 4f, page.getMediaBox().getWidth(), 4f, GOLD);
                y = top - 22f;
                String run = fit(AuditReportLabels.dash(data.audit().getDisplayId())
                        + "   " + AuditReportLabels.dash(data.audit().getName()), regular, 8f, contentWidth());
                draw(MARGIN, y, run, regular, 8f, MUTED);
                y -= 6f;
                strokeH(MARGIN, y, contentWidth(), HAIR);
                y -= 16f;
            }
        }

        private void ensure(float needed) throws IOException {
            if (y - needed < MARGIN + FOOTER) {
                newPage(false);
            }
        }

        private float contentWidth() {
            return page.getMediaBox().getWidth() - 2 * MARGIN;
        }

        private void fill(float x, float yBottom, float w, float h, float[] color) throws IOException {
            stream.setNonStrokingColor(color[0], color[1], color[2]);
            stream.addRect(x, yBottom, w, h);
            stream.fill();
        }

        private void strokeRect(float x, float yBottom, float w, float h, float[] color) throws IOException {
            stream.setStrokingColor(color[0], color[1], color[2]);
            stream.setLineWidth(0.6f);
            stream.addRect(x, yBottom, w, h);
            stream.stroke();
        }

        private void strokeH(float x, float yLine, float w, float[] color) throws IOException {
            stream.setStrokingColor(color[0], color[1], color[2]);
            stream.setLineWidth(0.8f);
            stream.moveTo(x, yLine);
            stream.lineTo(x + w, yLine);
            stream.stroke();
        }

        private List<String> wrap(String text, PDType1Font font, float size, float maxWidth) throws IOException {
            String safe = PdfText.oneLine(text);
            if (safe.isEmpty()) {
                return List.of("-");
            }
            List<String> lines = new ArrayList<>();
            StringBuilder line = new StringBuilder();
            for (String word : safe.split(" ")) {
                if (word.isEmpty()) {
                    continue;
                }
                if (width(font, size, word) > maxWidth) {
                    if (!line.isEmpty()) {
                        lines.add(line.toString());
                        line.setLength(0);
                    }
                    String rest = word;
                    while (!rest.isEmpty()) {
                        int n = fitCount(font, size, rest, maxWidth);
                        if (n <= 0) {
                            n = 1;
                        }
                        if (n >= rest.length()) {
                            line.append(rest);
                            rest = "";
                        } else {
                            lines.add(rest.substring(0, n));
                            rest = rest.substring(n);
                        }
                    }
                    continue;
                }
                String candidate = line.isEmpty() ? word : line + " " + word;
                if (width(font, size, candidate) <= maxWidth) {
                    line.setLength(0);
                    line.append(candidate);
                } else {
                    lines.add(line.toString());
                    line.setLength(0);
                    line.append(word);
                }
            }
            if (!line.isEmpty()) {
                lines.add(line.toString());
            }
            return lines.isEmpty() ? List.of("-") : lines;
        }

        private String fit(String text, PDType1Font font, float size, float maxWidth) throws IOException {
            String safe = PdfText.oneLine(text);
            if (safe.isEmpty()) {
                return "-";
            }
            if (width(font, size, safe) <= maxWidth) {
                return safe;
            }
            String ellipsis = "...";
            int end = safe.length();
            while (end > 0 && width(font, size, safe.substring(0, end) + ellipsis) > maxWidth) {
                end--;
            }
            return end <= 0 ? ellipsis : safe.substring(0, end) + ellipsis;
        }

        private int fitCount(PDType1Font font, float size, String text, float maxWidth) throws IOException {
            int lo = 1;
            int hi = text.length();
            int best = 1;
            while (lo <= hi) {
                int mid = (lo + hi) / 2;
                if (width(font, size, text.substring(0, mid)) <= maxWidth) {
                    best = mid;
                    lo = mid + 1;
                } else {
                    hi = mid - 1;
                }
            }
            return best;
        }

        private float width(PDType1Font font, float size, String text) throws IOException {
            return font.getStringWidth(text) / 1000f * size;
        }

        private static String person(String name, String email) {
            String n = AuditReportLabels.dash(name);
            if (email == null || email.isBlank()) {
                return n;
            }
            if ("-".equals(n)) {
                return email.trim();
            }
            return n + " (" + email.trim() + ")";
        }

        void closeStream() throws IOException {
            if (stream != null) {
                stream.close();
                stream = null;
            }
        }

        void stampFooters() throws IOException {
            int n = doc.getNumberOfPages();
            String classification = "Classification: " + AuditReportLabels.dash(data.classification());
            String id = AuditReportLabels.dash(data.audit().getDisplayId());
            for (int i = 0; i < n; i++) {
                PDPage p = doc.getPage(i);
                try (PDPageContentStream footer = new PDPageContentStream(
                        doc, p, PDPageContentStream.AppendMode.APPEND, true, true)) {
                    float pageW = p.getMediaBox().getWidth();
                    footer.setStrokingColor(HAIR[0], HAIR[1], HAIR[2]);
                    footer.setLineWidth(0.4f);
                    footer.moveTo(MARGIN, 32f);
                    footer.lineTo(pageW - MARGIN, 32f);
                    footer.stroke();
                    String pageNo = "Page " + (i + 1) + " of " + n;
                    float pageNoW = regular.getStringWidth(pageNo) / 1000f * 8f;
                    float idW = regular.getStringWidth(PdfText.oneLine(id)) / 1000f * 8f;
                    drawFooter(footer, MARGIN, 20f, fit(classification, regular, 8f, contentWidth() * 0.46f), regular);
                    drawFooter(footer, (pageW - idW) / 2f, 20f, PdfText.oneLine(id), regular);
                    drawFooter(footer, pageW - MARGIN - pageNoW, 20f, pageNo, regular);
                }
            }
        }

        private void drawFooter(PDPageContentStream footer, float x, float baseline, String value, PDType1Font font)
                throws IOException {
            footer.setNonStrokingColor(MUTED[0], MUTED[1], MUTED[2]);
            footer.beginText();
            footer.setFont(font, 8f);
            footer.newLineAtOffset(x, baseline);
            footer.showText(value);
            footer.endText();
        }
    }
}

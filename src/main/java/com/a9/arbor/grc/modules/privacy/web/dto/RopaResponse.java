package com.a9.arbor.grc.modules.privacy.web.dto;

import com.a9.arbor.grc.modules.privacy.domain.PrivacyRopa;
import com.a9.arbor.grc.modules.privacy.domain.RopaDesignation;
import com.a9.arbor.grc.modules.privacy.domain.RopaDpiaStatus;
import com.a9.arbor.grc.modules.privacy.domain.RopaIntakeMode;
import com.a9.arbor.grc.modules.privacy.domain.RopaLegalBasis;
import com.a9.arbor.grc.modules.privacy.domain.RopaReviewOutcome;
import com.a9.arbor.grc.modules.privacy.domain.RopaHeadOutcome;
import com.a9.arbor.grc.modules.privacy.domain.RopaStatus;

import java.time.Instant;

public record RopaResponse(
        Long id,
        String displayId,
        String activityName,
        String entityName,
        String sectorName,
        String divisionName,
        String sectionName,
        String processingDescription,
        String purpose,
        RopaLegalBasis legalBasis,
        String dataCategories,
        String sensitiveDataCategories,
        String dataSubjects,
        String dataSubjectVolume,
        String dataSubjectVolumeNote,
        String processingFrequency,
        String processingFrequencyNote,
        String sourceOfPersonalData,
        String methodOfReceiving,
        String recipients,
        boolean shareInternal,
        String shareInternalDetails,
        boolean shareOperator,
        String shareOperatorDetails,
        boolean shareExternal,
        String shareExternalDetails,
        String externalEntityLocation,
        boolean thirdCountryTransfers,
        Boolean adequateProtection,
        String crossBorderTransferBasis,
        String safeguardsImplemented,
        RopaDpiaStatus dpiaStatus,
        boolean dpiaRequired,
        Long linkedDpiaId,
        String thirdCountryTransferDetails,
        String retentionPeriod,
        String securityMeasures,
        String storageSystems,
        String representativeName,
        String representativeEmployeeId,
        String comments,
        String dpiaComments,
        Boolean dpiaCritLargeSensitive,
        Boolean dpiaCritSystematicAssessment,
        Boolean dpiaCritAutomatedProfiling,
        Boolean dpiaCritLegalSeriousImpact,
        RopaDesignation designation,
        RopaIntakeMode intakeMode,
        Long ropaDepartmentId,
        boolean draft,
        RopaReviewOutcome reviewOutcome,
        String legalBasesJson,
        String adequacyNote,
        Long orgUnitId,
        Long assignedContributorId,
        Long workTaskId,
        Instant assignedAt,
        RopaStatus status,
        String reviewNotes,
        Long reviewedByUserId,
        Instant reviewedAt,
        RopaHeadOutcome headOutcome,
        String headComments,
        Long headDecidedByUserId,
        Instant headDecidedAt,
        Long createdByUserId,
        Instant createdAt,
        Instant updatedAt
) {
    public static RopaResponse from(PrivacyRopa e) {
        return new RopaResponse(
                e.getId(),
                e.getDisplayId(),
                e.getActivityName(),
                e.getEntityName(),
                e.getSectorName(),
                e.getDivisionName(),
                e.getSectionName(),
                e.getProcessingDescription(),
                e.getPurpose(),
                e.getLegalBasis(),
                e.getDataCategories(),
                e.getSensitiveDataCategories(),
                e.getDataSubjects(),
                e.getDataSubjectVolume(),
                e.getDataSubjectVolumeNote(),
                e.getProcessingFrequency(),
                e.getProcessingFrequencyNote(),
                e.getSourceOfPersonalData(),
                e.getMethodOfReceiving(),
                e.getRecipients(),
                e.isShareInternal(),
                e.getShareInternalDetails(),
                e.isShareOperator(),
                e.getShareOperatorDetails(),
                e.isShareExternal(),
                e.getShareExternalDetails(),
                e.getExternalEntityLocation(),
                e.isThirdCountryTransfers(),
                e.getAdequateProtection(),
                e.getCrossBorderTransferBasis(),
                e.getSafeguardsImplemented(),
                e.getDpiaStatus(),
                e.isDpiaRequired() || e.needsApprovedDpia(),
                e.getLinkedDpiaId(),
                e.getThirdCountryTransferDetails(),
                e.getRetentionPeriod(),
                e.getSecurityMeasures(),
                e.getStorageSystems(),
                e.getRepresentativeName(),
                e.getRepresentativeEmployeeId(),
                e.getComments(),
                e.getDpiaComments(),
                e.getDpiaCritLargeSensitive(),
                e.getDpiaCritSystematicAssessment(),
                e.getDpiaCritAutomatedProfiling(),
                e.getDpiaCritLegalSeriousImpact(),
                e.getDesignation(),
                e.getIntakeMode(),
                e.getRopaDepartmentId(),
                e.isDraft(),
                e.getReviewOutcome(),
                e.getLegalBasesJson(),
                e.getAdequacyNote(),
                e.getOrgUnitId(),
                e.getAssignedContributorId(),
                e.getWorkTaskId(),
                e.getAssignedAt(),
                e.getStatus(),
                e.getReviewNotes(),
                e.getReviewedByUserId(),
                e.getReviewedAt(),
                e.getHeadOutcome() != null ? e.getHeadOutcome() : RopaHeadOutcome.PENDING,
                e.getHeadComments(),
                e.getHeadDecidedByUserId(),
                e.getHeadDecidedAt(),
                e.getCreatedByUserId(),
                e.getCreatedAt(),
                e.getUpdatedAt());
    }
}

package com.a9.arbor.grc.modules.export;

import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.function.Consumer;

/**
 * Shared PDFBox layout for Reports hub PDFs (req §19.3: classification footer, cover meta).
 * Pattern mirrors AuditReportPdfWriter / RecoveryPlanPdfWriter (close stream before save).
 */
public final class ReportPdfSupport {

    private static final float MARGIN = 50f;
    private static final float FOOTER_Y = 30f;
    private static final float LINE = 12f;
    private static final DateTimeFormatter DT =
            DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm 'UTC'").withZone(ZoneOffset.UTC);

    private ReportPdfSupport() {
    }

    public static byte[] write(String orgName,
                               String title,
                               String generatedBy,
                               String classificationFooter,
                               Consumer<PageWriter> body) {
        try (PDDocument doc = new PDDocument()) {
            PDType1Font titleFont = new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD);
            PDType1Font bodyFont = new PDType1Font(Standard14Fonts.FontName.HELVETICA);
            String footer = "Classification: "
                    + (classificationFooter == null || classificationFooter.isBlank()
                    ? "Confidential" : classificationFooter);

            PageWriter page = new PageWriter(doc, bodyFont, footer);
            page.newPage();
            page.writeTitle(titleFont, title);
            page.blank();
            page.writeLine("Organisation: " + safe(orgName));
            page.writeLine("Generated: " + DT.format(Instant.now()));
            if (generatedBy != null && !generatedBy.isBlank()) {
                page.writeLine("Generated by: " + generatedBy);
            }
            page.blank();
            body.accept(page);
            page.closeStream();

            ByteArrayOutputStream out = new ByteArrayOutputStream();
            doc.save(out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new IllegalStateException("Failed to generate report PDF: " + title, e);
        }
    }

    public static String safe(String s) {
        return s == null || s.isBlank() ? "-" : s;
    }

    public static String truncate(String s, int max) {
        if (s == null) {
            return "";
        }
        String t = s.replace('\n', ' ').trim();
        return t.length() <= max ? t : t.substring(0, max - 1) + "…";
    }

    public static final class PageWriter {
        private final PDDocument doc;
        private final PDType1Font bodyFont;
        private final String footer;
        private final PDType1Font headingFont;
        private PDPage page;
        private PDPageContentStream stream;
        private float y;

        PageWriter(PDDocument doc, PDType1Font bodyFont, String footer) {
            this.doc = doc;
            this.bodyFont = bodyFont;
            this.footer = footer;
            this.headingFont = new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD);
        }

        public void newPage() {
            try {
                closeStream();
                page = new PDPage(PDRectangle.A4);
                doc.addPage(page);
                stream = new PDPageContentStream(doc, page);
                y = page.getMediaBox().getHeight() - MARGIN;
                drawFooter();
            } catch (IOException e) {
                throw new IllegalStateException(e);
            }
        }

        public void writeTitle(PDType1Font font, String text) {
            try {
                stream.beginText();
                stream.setFont(font, 16);
                stream.newLineAtOffset(MARGIN, y);
                stream.showText(truncate(text, 80));
                stream.endText();
                y -= LINE * 2;
            } catch (IOException e) {
                throw new IllegalStateException(e);
            }
        }

        public void writeHeading(String text) {
            try {
                ensureSpace(2);
                stream.beginText();
                stream.setFont(headingFont, 12);
                stream.newLineAtOffset(MARGIN, y);
                stream.showText(truncate(text, 90));
                stream.endText();
                y -= LINE * 1.4f;
            } catch (IOException e) {
                throw new IllegalStateException(e);
            }
        }

        public void writeLine(String text) {
            try {
                ensureSpace(1);
                stream.beginText();
                stream.setFont(bodyFont, 9);
                stream.newLineAtOffset(MARGIN, y);
                stream.showText(truncate(text, 115));
                stream.endText();
                y -= LINE;
            } catch (IOException e) {
                throw new IllegalStateException(e);
            }
        }

        public void blank() {
            y -= LINE / 2;
        }

        /** Formal certification reports (SoA, BCP): signature block per req §19.3. */
        public void writeSignatureBlock() {
            newPage();
            writeHeading("Signatures");
            blank();
            writeLine("Prepared by (Admin): _________________________    Date: _______________");
            blank();
            writeLine("Approved by (Owner): _________________________    Date: _______________");
        }

        /**
         * Enterprise table: bordered grid, grey header band, zebra rows, column-aware truncation.
         */
        public void writeTable(String[] headers, List<String[]> rows, float[] colWeights) {
            try {
                ReportPdfTableRenderer.TableCursor cursor =
                        new ReportPdfTableRenderer.TableCursor(page, stream, y);
                cursor = ReportPdfTableRenderer.draw(
                        cursor,
                        MARGIN,
                        MARGIN + 20,
                        bodyFont,
                        headingFont,
                        headers,
                        rows,
                        colWeights,
                        () -> {
                            newPage();
                            return new ReportPdfTableRenderer.TableCursor(page, stream, y);
                        });
                y = cursor.y();
            } catch (IOException e) {
                throw new IllegalStateException(e);
            }
        }

        public void ensureSpace(int lines) {
            if (y - lines * LINE < MARGIN + 20) {
                newPage();
            }
        }

        private void drawFooter() throws IOException {
            stream.beginText();
            stream.setFont(bodyFont, 8);
            stream.newLineAtOffset(MARGIN, FOOTER_Y);
            stream.showText(truncate(footer, 80));
            stream.endText();
            stream.beginText();
            stream.setFont(bodyFont, 8);
            float pageNumX = page.getMediaBox().getWidth() - MARGIN - 40;
            stream.newLineAtOffset(pageNumX, FOOTER_Y);
            stream.showText("Page " + doc.getNumberOfPages());
            stream.endText();
        }

        void closeStream() throws IOException {
            if (stream != null) {
                stream.close();
                stream = null;
            }
        }
    }
}

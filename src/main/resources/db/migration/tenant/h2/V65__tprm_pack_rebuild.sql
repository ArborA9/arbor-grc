CREATE TABLE tprm_control (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    control_code        VARCHAR(16)   NOT NULL,
    domain              VARCHAR(80)   NOT NULL,
    requirement         VARCHAR(500)  NOT NULL,
    description         VARCHAR(4000) NOT NULL,
    required_evidence   VARCHAR(2000) NOT NULL,
    weight              INT           NOT NULL,
    weight_label        VARCHAR(32)   NOT NULL,
    mandatory           BOOLEAN       NOT NULL DEFAULT FALSE,
    asked_from_tier     INT           NOT NULL,
    iso27001            VARCHAR(120),
    uae_ia              VARCHAR(120),
    other_standard      VARCHAR(120),
    module              VARCHAR(16)   NOT NULL,
    sort_order          INT           NOT NULL,
    CONSTRAINT uq_tprm_control_code UNIQUE (control_code)
);


-- Append-only CAPA return (reject) history for Admin / Contributor review.
CREATE TABLE IF NOT EXISTS capa_return_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capa_id BIGINT NOT NULL,
    rejected_at TIMESTAMP NOT NULL,
    rejected_by_user_id BIGINT NOT NULL,
    reason CLOB NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_capa_return_event_capa ON capa_return_event (capa_id);

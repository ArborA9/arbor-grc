-- FCA Design × Performance control rows (ERM / Unified). Privacy keeps legacy CE field.

CREATE TABLE IF NOT EXISTS risk_control (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_id BIGINT NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    description VARCHAR(2000) NOT NULL,
    design VARCHAR(32) NOT NULL,
    performance VARCHAR(32) NOT NULL,
    control_gap VARCHAR(4000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_risk_control_risk FOREIGN KEY (risk_id) REFERENCES risk_record(id)
);

CREATE INDEX IF NOT EXISTS idx_risk_control_risk ON risk_control(risk_id);

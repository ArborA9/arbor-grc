-- DPIA journey from scratch (DPIA Journey.docx + Questionnaire v3 + DPO Assessment).
-- Replaces Mode A as the product DPIA path. Old privacy_dpia table retained for legacy rows.

CREATE TABLE dpia_questionnaire (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    description         VARCHAR(2000),
    system_default      BOOLEAN      NOT NULL DEFAULT FALSE,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by_user_id  BIGINT       NOT NULL,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dpia_questionnaire_question (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    questionnaire_id    BIGINT       NOT NULL,
    code                VARCHAR(16)  NOT NULL,
    section_name        VARCHAR(255) NOT NULL,
    principle           VARCHAR(255) NOT NULL,
    question_text       CLOB         NOT NULL,
    guidance            CLOB,
    response_type       VARCHAR(64)  NOT NULL,
    options_json        CLOB,
    sort_order          INT          NOT NULL DEFAULT 0,
    required_flag       BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_dpia_q_questionnaire ON dpia_questionnaire_question (questionnaire_id);

CREATE TABLE dpia_project (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(255) NOT NULL,
    assessment_year         INT,
    status                  VARCHAR(32)  NOT NULL DEFAULT 'DRAFT',
    linked_ropa_project_id  BIGINT,
    created_by_user_id      BIGINT       NOT NULL,
    created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dpia_department (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dpia_project_id         BIGINT       NOT NULL,
    org_unit_id             BIGINT       NOT NULL,
    reason_description      VARCHAR(4000),
    questionnaire_id        BIGINT,
    champion_user_id        BIGINT,
    department_head_user_id BIGINT,
    due_date                DATE,
    status                  VARCHAR(32)  NOT NULL DEFAULT 'NOT_STARTED',
    return_from             VARCHAR(16),
    return_reason           VARCHAR(4000),
    work_task_id            BIGINT,
    head_work_task_id       BIGINT,
    head_notes              VARCHAR(4000),
    head_decided_at         TIMESTAMP,
    head_outcome            VARCHAR(32)  DEFAULT 'PENDING',
    dpo_accepted_at         TIMESTAMP,
    dpo_accepted_by_user_id BIGINT,
    assessment_complete     BOOLEAN      NOT NULL DEFAULT FALSE,
    closed_at               TIMESTAMP,
    closed_by_user_id       BIGINT,
    created_by_user_id      BIGINT       NOT NULL,
    created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_dpia_dept_project ON dpia_department (dpia_project_id);
CREATE INDEX idx_dpia_dept_champion ON dpia_department (champion_user_id);
CREATE INDEX idx_dpia_dept_head ON dpia_department (department_head_user_id);

CREATE TABLE dpia_instance_question (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dpia_department_id  BIGINT       NOT NULL,
    code                VARCHAR(16)  NOT NULL,
    section_name        VARCHAR(255) NOT NULL,
    principle           VARCHAR(255) NOT NULL,
    question_text       CLOB         NOT NULL,
    guidance            CLOB,
    response_type       VARCHAR(64)  NOT NULL,
    options_json        CLOB,
    sort_order          INT          NOT NULL DEFAULT 0,
    required_flag       BOOLEAN      NOT NULL DEFAULT TRUE,
    answer_text         CLOB,
    answer_json         CLOB,
    details_evidence    CLOB
);

CREATE INDEX idx_dpia_inst_dept ON dpia_instance_question (dpia_department_id);

CREATE TABLE dpia_dpo_assessment_row (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dpia_department_id  BIGINT       NOT NULL,
    sort_order          INT          NOT NULL,
    principle           VARCHAR(255) NOT NULL,
    description_text    CLOB         NOT NULL,
    compliance_status   VARCHAR(64),
    remarks             CLOB,
    recommended_measures CLOB,
    risk_title          VARCHAR(500)
);

CREATE INDEX idx_dpia_dpo_dept ON dpia_dpo_assessment_row (dpia_department_id);

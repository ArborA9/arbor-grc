-- Excel SoT: named checklists per audit, working-paper rows, Admin CAPA tracker fields.

CREATE TABLE grc_audit_checklist (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_id     BIGINT       NOT NULL,
    template_key VARCHAR(32)  NOT NULL,
    name         VARCHAR(200) NOT NULL,
    sort_order   INT          NOT NULL DEFAULT 0,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_checklist_audit FOREIGN KEY (audit_id) REFERENCES grc_audit (id) ON DELETE CASCADE
);

CREATE INDEX idx_audit_checklist_audit ON grc_audit_checklist (audit_id);

ALTER TABLE grc_audit ADD COLUMN audit_standard VARCHAR(32);
UPDATE grc_audit SET audit_standard = 'ISO_27001' WHERE audit_standard IS NULL;

ALTER TABLE grc_audit ALTER COLUMN framework_id DROP NOT NULL;

ALTER TABLE grc_audit_checklist_item DROP CONSTRAINT IF EXISTS uq_grc_audit_item_node;
ALTER TABLE grc_audit_checklist_item ALTER COLUMN framework_node_id DROP NOT NULL;
ALTER TABLE grc_audit_checklist_item ALTER COLUMN node_code VARCHAR(80);
ALTER TABLE grc_audit_checklist_item ADD COLUMN checklist_id BIGINT;
ALTER TABLE grc_audit_checklist_item ADD COLUMN sort_order INT NOT NULL DEFAULT 0;
ALTER TABLE grc_audit_checklist_item ADD COLUMN soa_applicability VARCHAR(120);
ALTER TABLE grc_audit_checklist_item ADD COLUMN finding_description CLOB;
ALTER TABLE grc_audit_checklist_item ADD COLUMN library_locked BOOLEAN NOT NULL DEFAULT TRUE;

INSERT INTO grc_audit_checklist (audit_id, template_key, name, sort_order)
SELECT id, 'CUSTOM', CONCAT('Checklist ', COALESCE(framework_code, CAST(id AS VARCHAR))), 0
FROM grc_audit g
WHERE NOT EXISTS (SELECT 1 FROM grc_audit_checklist c WHERE c.audit_id = g.id);

UPDATE grc_audit_checklist_item i
SET checklist_id = (SELECT MIN(c.id) FROM grc_audit_checklist c WHERE c.audit_id = i.audit_id)
WHERE checklist_id IS NULL;

ALTER TABLE grc_audit_checklist_item ALTER COLUMN checklist_id SET NOT NULL;
ALTER TABLE grc_audit_checklist_item ADD CONSTRAINT fk_audit_item_checklist
    FOREIGN KEY (checklist_id) REFERENCES grc_audit_checklist (id);

ALTER TABLE capa ADD COLUMN correction CLOB;
ALTER TABLE capa ADD COLUMN evidence_required CLOB;

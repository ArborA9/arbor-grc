-- ROPA project journey (client Ropa Journey.docx + RoPA.xlsx), DPIA In Progress, Data Privacy Risk.

CREATE TABLE ropa_project (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    status              VARCHAR(32)  NOT NULL DEFAULT 'DRAFT',
    created_by_user_id  BIGINT       NOT NULL,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ropa_department (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ropa_project_id       BIGINT       NOT NULL,
    org_unit_id           BIGINT       NOT NULL,
    department_head_user_id BIGINT,
    champion_user_id      BIGINT,
    due_date              DATE,
    status                VARCHAR(32)  NOT NULL DEFAULT 'NOT_STARTED',
    return_from           VARCHAR(16),
    return_reason         VARCHAR(4000),
    work_task_id          BIGINT,
    head_work_task_id     BIGINT,
    head_notes            VARCHAR(4000),
    head_decided_at       TIMESTAMP,
    closed_at             TIMESTAMP,
    closed_by_user_id     BIGINT,
    created_by_user_id    BIGINT       NOT NULL,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ropa_dept_project ON ropa_department (ropa_project_id);
CREATE INDEX idx_ropa_dept_champion ON ropa_department (champion_user_id);
CREATE INDEX idx_ropa_dept_head ON ropa_department (department_head_user_id);

ALTER TABLE privacy_ropa ADD COLUMN IF NOT EXISTS ropa_department_id BIGINT;
ALTER TABLE privacy_ropa ADD COLUMN IF NOT EXISTS review_outcome VARCHAR(32) DEFAULT 'OPEN';
ALTER TABLE privacy_ropa ADD COLUMN IF NOT EXISTS legal_bases_json CLOB;
ALTER TABLE privacy_ropa ADD COLUMN IF NOT EXISTS adequacy_note VARCHAR(2000);

CREATE INDEX idx_privacy_ropa_dept ON privacy_ropa (ropa_department_id);

ALTER TABLE risk_record ADD COLUMN IF NOT EXISTS source_dpia_id BIGINT;
ALTER TABLE risk_record ADD COLUMN IF NOT EXISTS source_ropa_id BIGINT;


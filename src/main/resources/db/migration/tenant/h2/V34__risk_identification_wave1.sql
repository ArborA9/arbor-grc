-- Risk Wave 1: identification fidelity (§13.2) — UAE IA priority, ID override flags,
-- auto-close override, Gap→Risk source link, additional framework mappings.

ALTER TABLE risk_record ADD uae_ia_priority VARCHAR(8);
ALTER TABLE risk_record ADD display_id_overridden BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE risk_record ADD auto_close_override BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE risk_record ADD auto_close_override_justification CLOB;
ALTER TABLE risk_record ADD source_gap_assessment_id BIGINT;
ALTER TABLE risk_record ADD source_gap_item_id BIGINT;

CREATE INDEX idx_risk_source_gap ON risk_record (source_gap_assessment_id, source_gap_item_id);

CREATE TABLE risk_framework_mapping (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_id            BIGINT       NOT NULL,
    framework_id       BIGINT       NOT NULL,
    framework_code     VARCHAR(64),
    framework_node_id  BIGINT,
    control_ref        VARCHAR(100),
    custom_ref         VARCHAR(512),
    created_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rfm_risk FOREIGN KEY (risk_id) REFERENCES risk_record (id)
);

CREATE INDEX idx_rfm_risk ON risk_framework_mapping (risk_id);


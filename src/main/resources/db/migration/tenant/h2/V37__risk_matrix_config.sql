-- Risk Wave 4: tenant-customisable risk matrices (§13.3 B6/B7).

CREATE TABLE risk_matrix_config (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inherent_json        CLOB         NOT NULL,
    residual_json        CLOB         NOT NULL,
    version              INT          NOT NULL DEFAULT 1,
    change_reason        VARCHAR(1000),
    updated_by_user_id   BIGINT,
    updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO notification_template (trigger_type, subject_template, body_template, channel_email, channel_in_app, version, is_active)
SELECT 'RISK_MATRIX_CHANGED',
       '[FYI] - Risk matrix updated - Risk',
       'The tenant risk matrices were updated (version {{version}}). Reason: {{reason}}. Existing risk scores are not recalculated.',
       TRUE, TRUE, 1, TRUE
WHERE NOT EXISTS (SELECT 1 FROM notification_template WHERE trigger_type = 'RISK_MATRIX_CHANGED');

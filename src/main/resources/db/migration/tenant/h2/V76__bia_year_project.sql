-- BIA year project + Head workflow columns. Nest existing cycles into a project by issue year.

CREATE TABLE IF NOT EXISTS bia_project (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_year         INT          NOT NULL,
    name                    VARCHAR(255) NOT NULL,
    status                  VARCHAR(32)  NOT NULL DEFAULT 'OPEN',
    created_by_user_id      BIGINT       NOT NULL,
    created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_bia_project_year UNIQUE (assessment_year)
);

CREATE INDEX idx_bia_project_status ON bia_project (status);

INSERT INTO bia_project (assessment_year, name, status, created_by_user_id, created_at, updated_at)
SELECT
    y.assessment_year,
    'BIA ' || CAST(y.assessment_year AS VARCHAR),
    'OPEN',
    COALESCE(y.created_by, 1),
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP
FROM (
    SELECT
        COALESCE(YEAR(c.issue_date), YEAR(c.created_at), YEAR(CURRENT_TIMESTAMP)) AS assessment_year,
        MIN(c.created_by_user_id) AS created_by
    FROM bia_cycle c
    GROUP BY COALESCE(YEAR(c.issue_date), YEAR(c.created_at), YEAR(CURRENT_TIMESTAMP))
) y
WHERE NOT EXISTS (SELECT 1 FROM bia_project p WHERE p.assessment_year = y.assessment_year);

ALTER TABLE bia_cycle ADD COLUMN IF NOT EXISTS bia_project_id BIGINT;
ALTER TABLE bia_cycle ADD COLUMN IF NOT EXISTS bc_head_user_id BIGINT;
ALTER TABLE bia_cycle ADD COLUMN IF NOT EXISTS bc_head_notes VARCHAR(4000);
ALTER TABLE bia_cycle ADD COLUMN IF NOT EXISTS bc_head_decided_at TIMESTAMP;
ALTER TABLE bia_cycle ADD COLUMN IF NOT EXISTS admin_forward_notes VARCHAR(4000);
ALTER TABLE bia_cycle ADD COLUMN IF NOT EXISTS closed_at TIMESTAMP;
ALTER TABLE bia_cycle ADD COLUMN IF NOT EXISTS closed_by_user_id BIGINT;
ALTER TABLE bia_cycle ADD COLUMN IF NOT EXISTS bc_head_work_task_id BIGINT;

UPDATE bia_cycle c
SET bia_project_id = (
    SELECT p.id FROM bia_project p
    WHERE p.assessment_year = COALESCE(YEAR(c.issue_date), YEAR(c.created_at), YEAR(CURRENT_TIMESTAMP))
);

-- Cycles with no resolvable project (should not happen after INSERT); orphan-safe default year project.
INSERT INTO bia_project (assessment_year, name, status, created_by_user_id, created_at, updated_at)
SELECT YEAR(CURRENT_TIMESTAMP), 'BIA ' || CAST(YEAR(CURRENT_TIMESTAMP) AS VARCHAR), 'OPEN', 1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
WHERE EXISTS (SELECT 1 FROM bia_cycle WHERE bia_project_id IS NULL)
  AND NOT EXISTS (SELECT 1 FROM bia_project WHERE assessment_year = YEAR(CURRENT_TIMESTAMP));

UPDATE bia_cycle
SET bia_project_id = (SELECT id FROM bia_project WHERE assessment_year = YEAR(CURRENT_TIMESTAMP))
WHERE bia_project_id IS NULL;

UPDATE bia_cycle SET status = 'CLOSED' WHERE status = 'APPROVED';

ALTER TABLE bia_cycle ALTER COLUMN bia_project_id SET NOT NULL;

ALTER TABLE bia_cycle DROP CONSTRAINT IF EXISTS fk_bia_cycle_project;
ALTER TABLE bia_cycle ADD CONSTRAINT fk_bia_cycle_project FOREIGN KEY (bia_project_id) REFERENCES bia_project (id);

CREATE INDEX IF NOT EXISTS idx_bia_cycle_project ON bia_cycle (bia_project_id);

